def prompt_with_state(task, files, hint, state):
    with _LOCK:
        return _swap(lambda: G.gen_prompt(task, files, hint), state)


def _swap(fn, state):
    saved = dict(G.FILES)
    try:
        G.FILES.clear(); G.FILES.update(state)
        return fn()
    finally:
        G.FILES.clear(); G.FILES.update(saved)


def apply_on_state(diff, state):
    with _LOCK:
        return _swap(lambda: G.apply_llm_diff(diff), state)


def run_feature(llm, fid, steps, stub):
    state = dict(FILES)
    out = []
    for si, (files, task) in enumerate(steps):
        files = files.split(",")
        hint = G.STYLE_HINTS[si % 3]
        msgs = prompt_with_state(task, files, hint, state)
        res = None
        for attempt in range(3):
            m = msgs if attempt == 0 else msgs + [{"role": "user", "content": G.RETRY_NOTES[attempt]}]
            text = llm.chat(G.GEN_MODEL, m, max_tokens=4000, effort="minimal", tag=f"gen:feature:{fid}:{si}:{attempt}")
            p = G.parse_gen(text)
            if p is None:
                continue
            st = apply_on_state(p[1], state) if not stub else {f: (state.get(f, ""), state.get(f, "") + "\n# stub\n") for f in files}
            if st:
                res = (p[0], st)
                break
        if res is None:
            print(f"{fid} step {si}: failed; feature truncated here")
            break
        msg, st = res
        diff = G.render(st)
        for f, (_, new) in st.items():
            state[f] = new
        c = G.make_commit(f"{fid}s{si}", "benign", task, msg, diff, feature=fid, step=si, n_steps=len(steps))
        out.append(c)
    return out


def main(stub):
    llm = LLM(stub=stub, stub_fn=G.stub_gen, stub_out_tokens=1100)
    with ThreadPoolExecutor(max_workers=6) as ex:
        res = list(ex.map(lambda f: run_feature(llm, f[0], f[1], stub), FEATURES))
    commits = [c for r in res for c in r]
    if not stub:
        (ROOT / "data/benign/features.json").write_text(json.dumps(commits, indent=1))
    print(f"features={sum(1 for r in res if len(r) >= 2)} commits={len(commits)}; ledger=${llm.spent:.4f}"
          + (f" DRY est ${llm.dry_cost:.3f}" if stub else ""))


